// 查「位置 + 角色 + 重心」的热区。side 传 "L"/"R" 时优先取中轴线位置的左右变体（该组合没有变体就用默认那套）；
// 未知组合返回 null。
export function heatOf(
  position: string,
  role: string,
  focus: string,
  side?: "L" | "R" | null,
): number[] | null {
  const key = `${position} ${role}/${focus}`;
  const raw = (side === "L" || side === "R" ? ROLE_HEAT_SIDE[key]?.[side === "L" ? 0 : 1] : null) ?? ROLE_HEAT[key];
  return raw ? [...raw].map(Number) : null;
}
