// 公开页自动轮询的间隔。
//
// 下限 60s 不是随手取的：这些轮询打的读面都走 worker/routes/public.ts 的 pubCache，
// TTL 就是 60s（/live、轮次场次、单场详情）。比 TTL 更密的轮询里必然有一部分落在同一个
// 缓存窗口内、拿到的是和上一轮逐字相同的数据——白烧请求，也白占 Workers 请求配额。
// 60s 是与服务端缓存对齐后仍能每轮都可能有新数据的最快节奏。
//
// 上限不再拉长：一场球的比分最多晚一分钟出现，是「直播」还能接受的边界；再往 90s 起
// 就开始像页面卡住了。想再降读量的正路是抬服务端 TTL，而不是让观众多等。
export const POLL_MS = 60_000;
