// 积分榜重算自愈（v5.8.0）：主写入与「后续处理欠账」标记同批提交，后续处理（榜重算 / 晋级填位 /
// 下一阶段首轮生成）失败时不再留下静默的半截状态（病根与协议见
// docs/superpowers/specs/2026-10-15-standings-rebuild-self-heal-design.md）。
//
// 依赖方向：本文件只 import lib/standings。下一阶段首轮生成器（buildAutoFillStmts）住在
// routes/admin/schedule.ts，由调用方以参数注入——否则 lib 与 routes 互相 import 成环。
import {
  AdvancerError,
  buildAdvanceStmts,
  buildStandingsChainStmts,
  buildStandingsForStagesStmts,
} from "./standings";

// 触发点：六个写入点（五类链）。存进 rebuild_pending.source 只为排查时能追源头。
export type RebuildSource =
  | "scoring" // 报分/改判/弃权（scoring.ts）
  | "carry" // 带入积分配置（schedule.ts）
  | "generate" // 生成赛程（schedule.ts）
  | "delete_match" // 删单场（schedule.ts）
  | "delete_stage" // 一键清除阶段场次（schedule.ts）
  | "deduction"; // 扣分整表替换（tournaments.ts）

export interface PendingRebuildMark {
  stageId: number;
  tournamentId: number;
  source: RebuildSource;
}

// 一批后续处理语句。必须是「函数」而不是现成数组：自动生成那一批要等前一批提交后
// 才能构建（回填取人读的是重算后的榜——scoring.ts 里 D1 缺陷的教训）。
export type FollowUpStep = () => Promise<D1PreparedStatement[]>;

// 下一阶段首轮生成器（routes/admin/schedule.ts 的 buildAutoFillStmts）。
export type AutoFillBuilder = (
  env: { DB: D1Database },
  tournamentId: number,
  prevStageId: number
) => Promise<D1PreparedStatement[]>;

export interface RebuildGuardResult {
  followUpOk: boolean;
  error?: string;
}

const errText = (e: unknown): string => (e instanceof Error ? e.message : String(e));

// 标记与主写入同批：ON CONFLICT 只刷新 source，保留 created_at（欠账年龄）与 attempts（失败次数）。
// stage_id 是行的身份——同一阶段并发写入天然收敛成一行。
export function pendingMarkStmt(db: D1Database, mark: PendingRebuildMark): D1PreparedStatement {
  return db
    .prepare(
      `INSERT INTO rebuild_pending (stage_id, tournament_id, source)
       VALUES (?, ?, ?)
       ON CONFLICT(stage_id) DO UPDATE SET source = excluded.source`
    )
    .bind(mark.stageId, mark.tournamentId, mark.source);
}

export function pendingClearStmt(db: D1Database, stageId: number): D1PreparedStatement {
  return db.prepare("DELETE FROM rebuild_pending WHERE stage_id = ?").bind(stageId);
}

// 补跑一个阶段的欠账：与当初触发时的后续处理同范围、同顺序。
export function stageFollowUpSteps(
  db: D1Database,
  mark: PendingRebuildMark,
  opts?: { autoFill?: AutoFillBuilder }
): FollowUpStep[] {
  const first: FollowUpStep = async () => {
    const st = await db
      .prepare("SELECT kind FROM stage WHERE id = ?")
      .bind(mark.stageId)
      .first<{ kind: string }>();
    // 阶段已被删除（欠账还挂着）：退化成全赛事重算，别留「标记在、榜没修」的僵局
    if (!st) return buildStandingsForStagesStmts(db, mark.tournamentId, [null]);
    if (st.kind === "elim") {
      // 晋级填位只在报分链上；删除场次等其他触发点沿用现状：走榜链
      // （淘汰阶段自身无榜，重算的是排在它后面的积分阶段）
      return mark.source === "scoring"
        ? buildAdvanceStmts(db, mark.stageId)
        : buildStandingsChainStmts(db, mark.stageId);
    }
    return buildStandingsChainStmts(db, mark.stageId);
  };
  if (mark.source !== "scoring" || !opts?.autoFill) return [first];
  return [
    first,
    async () => {
      const st = await db
        .prepare("SELECT kind FROM stage WHERE id = ?")
        .bind(mark.stageId)
        .first<{ kind: string }>();
      if (!st || st.kind === "elim") return [];
      return opts.autoFill!({ DB: db }, mark.tournamentId, mark.stageId);
    },
  ];
}

// 后续处理：瞬时失败（网络抖动/实例中断）就地重试一次——重试会重读重算，不重放上一轮的语句。
// 仍失败则抛出，由调用方决定降级还是回滚。
async function runStageFollowUp(
  db: D1Database,
  mark: PendingRebuildMark,
  opts?: {
    firstBatchExtra?: D1PreparedStatement[];
    onAutoGenerated?: () => void;
    autoFill?: AutoFillBuilder;
  }
): Promise<void> {
  let lastError: unknown = null;
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      const steps = stageFollowUpSteps(db, mark, { autoFill: opts?.autoFill });
      // 审计等语句必须跟着第一个真实批次提交（不能单独跑空批丢账）
      let extra = [...(opts?.firstBatchExtra ?? [])];
      let index = 0;
      for (const step of steps) {
        const stmts = await step();
        const isAuto = index > 0;
        index++;
        if (stmts.length === 0 && extra.length === 0) continue;
        await db.batch([...stmts, ...extra]);
        if (isAuto) opts?.onAutoGenerated?.();
        extra = [];
      }
      if (extra.length > 0) await db.batch(extra);
      return;
    } catch (e) {
      // 语义冲突（下游已开打需换人）不是「补跑没跑完」，不能靠重试或降级糊过去：
      // 立刻交给调用方（scoring 回滚终场写入并清标记）
      if (e instanceof AdvancerError) throw e;
      lastError = e;
    }
  }
  throw lastError ?? new Error("后续处理失败");
}

async function recordFollowUpFailure(db: D1Database, stageId: number, e: unknown): Promise<void> {
  await db
    .prepare("UPDATE rebuild_pending SET attempts = attempts + 1, last_error = ? WHERE stage_id = ?")
    .bind(errText(e).slice(0, 500), stageId)
    .run()
    .catch(() => {});
}

/**
 * 六触发点的统一写入口：主写入 + 标记同批 → 后续处理（重试一次）→ 销账。
 *
 * 返回值只表达「后续处理是否跑完」：
 *   followUpOk=false → 已降级（标记留库，cron 兜底）；报分接口据此回 standingsPending。
 * AdvancerError 原样抛出：调用方回滚主写入，并把标记一并删掉（没有欠账）。
 */
export async function runStageRebuildGuard(
  db: D1Database,
  mark: PendingRebuildMark,
  writeStmts: D1PreparedStatement[],
  opts?: {
    firstBatchExtra?: D1PreparedStatement[];
    onAutoGenerated?: () => void;
    autoFill?: AutoFillBuilder;
  }
): Promise<RebuildGuardResult> {
  // 1) 主写入与标记同批：要么一起生效，要么一起不生效——不能出现「改了榜的输入已落库、
  //    却没人记得要重算」的静默状态（193 事故就是这样丢的）
  await db.batch([...writeStmts, pendingMarkStmt(db, mark)]);

  // 2) 后续处理
  try {
    await runStageFollowUp(db, mark, opts);
  } catch (e) {
    if (e instanceof AdvancerError) throw e;
    const msg = errText(e);
    await recordFollowUpFailure(db, mark.stageId, e);
    return { followUpOk: false, error: msg };
  }

  // 3) 销账：后续处理全部成功之后单独一批删除。销账失败不影响结果（重算幂等，cron 还会再补一次），
  //    只把原因记在标记上，便于管理端体检看到「处理已跑完、账没销掉」
  try {
    await db.batch([pendingClearStmt(db, mark.stageId)]);
  } catch (e) {
    await db
      .prepare("UPDATE rebuild_pending SET last_error = ? WHERE stage_id = ?")
      .bind(`销账失败：${errText(e)}`.slice(0, 500), mark.stageId)
      .run()
      .catch(() => {});
  }
  return { followUpOk: true };
}

/**
 * cron 兜底：把 rebuild_pending 里的欠账按阶段补跑干净。
 * 单行失败只记 attempts/last_error 并继续下一行；整体吞异常记日志（cron 没有重试，
 * 一次网络抖动不该把这次调度记成失败——与 runRosterSync 等任务同口径）。
 */
export async function healPendingRebuilds(
  env: { DB: D1Database },
  opts?: { autoFill?: AutoFillBuilder; logger?: (message: string) => void }
): Promise<{ healed: number; failed: number }> {
  const log = opts?.logger ?? ((m: string) => console.log(m));
  const result = { healed: 0, failed: 0 };
  try {
    const rows = await env.DB.prepare(
      "SELECT stage_id, tournament_id, source FROM rebuild_pending ORDER BY created_at, stage_id"
    ).all<{ stage_id: number; tournament_id: number; source: string }>();
    for (const r of rows.results ?? []) {
      const mark: PendingRebuildMark = {
        stageId: r.stage_id,
        tournamentId: r.tournament_id,
        source: r.source as RebuildSource,
      };
      try {
        await runStageFollowUp(env.DB, mark, { autoFill: opts?.autoFill });
        await env.DB.batch([pendingClearStmt(env.DB, mark.stageId)]);
        result.healed++;
      } catch (e) {
        await recordFollowUpFailure(env.DB, mark.stageId, e);
        result.failed++;
        log(`[rebuild-heal] 阶段 ${mark.stageId}（${mark.source}）补跑失败：${errText(e)}`);
      }
    }
  } catch (e) {
    log(`[rebuild-heal] 欠账扫描失败：${errText(e)}`);
  }
  return result;
}

// ---------- 管理端体检 ----------

export interface PendingRebuildRow {
  stageId: number;
  stageName: string | null;
  source: string;
  createdAt: string;
  attempts: number;
  lastError: string | null;
}

export async function listPendingRebuilds(
  db: D1Database,
  tournamentId: number
): Promise<PendingRebuildRow[]> {
  const res = await db
    .prepare(
      `SELECT p.stage_id AS stageId, s.name AS stageName, p.source, p.created_at AS createdAt,
              p.attempts, p.last_error AS lastError
       FROM rebuild_pending p LEFT JOIN stage s ON s.id = p.stage_id
       WHERE p.tournament_id = ?
       ORDER BY p.created_at, p.stage_id`
    )
    .bind(tournamentId)
    .all<PendingRebuildRow>();
  return res.results ?? [];
}

export interface StandingsMismatchRow {
  stageId: number;
  stageName: string | null;
  entryId: number;
  teamName: string | null;
  played: number;
  expected: number;
  carriedPlayed: number;
}

/**
 * 对账软信号：榜上的 played 应等于「本阶段完赛场次 + 带入基数」。
 * 镜像 computeStageStandings 的跳过规则——只数「两边都在该阶段榜上」的完赛场次，
 * 否则 scope 取人/沿用旧行等边界会变成假阳性（精确等式的意义就在这）。
 */
export async function findStandingsMismatches(
  db: D1Database,
  tournamentId: number
): Promise<StandingsMismatchRow[]> {
  const res = await db
    .prepare(
      `WITH pairs AS (
         SELECT m.stage_id, m.home_entry_id AS home, m.away_entry_id AS away
         FROM match m
         WHERE m.status = 'finished' AND m.home_entry_id IS NOT NULL AND m.away_entry_id IS NOT NULL
       ),
       counted AS (
         SELECT stage_id, entry_id, COUNT(*) AS n FROM (
           SELECT p.stage_id, p.home AS entry_id FROM pairs p
           WHERE EXISTS (SELECT 1 FROM standing rh WHERE rh.stage_id = p.stage_id AND rh.entry_id = p.home)
             AND EXISTS (SELECT 1 FROM standing ra WHERE ra.stage_id = p.stage_id AND ra.entry_id = p.away)
           UNION ALL
           SELECT p.stage_id, p.away FROM pairs p
           WHERE EXISTS (SELECT 1 FROM standing rh WHERE rh.stage_id = p.stage_id AND rh.entry_id = p.home)
             AND EXISTS (SELECT 1 FROM standing ra WHERE ra.stage_id = p.stage_id AND ra.entry_id = p.away)
         ) GROUP BY stage_id, entry_id
       )
       SELECT s.id AS stageId, s.name AS stageName, x.entry_id AS entryId, tm.name AS teamName,
              x.played AS played, x.carried_played AS carriedPlayed,
              COALESCE(c.n, 0) + x.carried_played AS expected
       FROM standing x
       JOIN stage s ON s.id = x.stage_id
       JOIN entry e ON e.id = x.entry_id
       LEFT JOIN team tm ON tm.id = e.team_id
       LEFT JOIN counted c ON c.stage_id = x.stage_id AND c.entry_id = x.entry_id
       WHERE s.tournament_id = ? AND s.kind != 'elim'
         AND x.played != COALESCE(c.n, 0) + x.carried_played
       ORDER BY s.sort_order, x.entry_id`
    )
    .bind(tournamentId)
    .all<StandingsMismatchRow>();
  return res.results ?? [];
}
